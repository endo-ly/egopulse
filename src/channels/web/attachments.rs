//! Web attachment snapshots: storage and authenticated delivery.

use std::path::Path;

use axum::body::Body;
use axum::extract::{Path as AxumPath, State};
use axum::http::{HeaderValue, Response, StatusCode, header};
use tokio_util::io::ReaderStream;
use uuid::Uuid;

use crate::attachment::AttachmentInfo;
use crate::channels::adapter::PreparedAttachment;
use crate::channels::utils::media;

use super::{ApiError, WebState, internal_error, not_found};

/// Attachments are private conversation content. Keep them out of persistent
/// browser caches; the Web UI already holds the fetched Blob for the mounted
/// card and fetches again when the file is needed later.
const ATTACHMENT_CACHE_CONTROL: &str = "private, no-store";

/// Upper bound for one Web attachment snapshot.
///
/// The value is a delivery policy, not a protocol limit: the Web UI fetches
/// the whole file as a Blob before playback, and the attachment tool holds the
/// bytes in memory while preparing them. 50 MiB covers roughly an hour of
/// 128 kbps audio while keeping those buffers bounded.
const MAX_WEB_ATTACHMENT_BYTES: usize = 50 * 1024 * 1024;

/// Validates the size of one Web attachment before it is written.
fn validate_web_attachment_size(size: usize) -> Result<(), String> {
    if size > MAX_WEB_ATTACHMENT_BYTES {
        return Err(format!(
            "attachment exceeds the {} MiB Web limit",
            MAX_WEB_ATTACHMENT_BYTES / (1024 * 1024)
        ));
    }
    Ok(())
}

/// Writes a snapshot with owner-only permissions where the platform supports
/// them. Attachments can contain private audio, so they must not be readable by
/// other local users even when the process umask is permissive.
async fn write_attachment_snapshot(path: &Path, bytes: &[u8]) -> std::io::Result<()> {
    let mut options = tokio::fs::OpenOptions::new();
    options.write(true).create_new(true);
    #[cfg(unix)]
    options.mode(0o600);
    let mut file = options.open(path).await?;
    tokio::io::AsyncWriteExt::write_all(&mut file, bytes).await?;
    tokio::io::AsyncWriteExt::flush(&mut file).await?;
    Ok(())
}

/// Snapshots a prepared attachment under `attachments_dir`.
///
/// The stored file is named by an opaque UUID plus the normalized extension.
/// The original file name is returned only as display metadata, so it cannot
/// influence the path.
pub(super) async fn store_attachment(
    attachments_dir: &Path,
    attachment: &PreparedAttachment,
) -> Result<AttachmentInfo, String> {
    let size = attachment.bytes().len();
    validate_web_attachment_size(size)?;

    let filename = attachment
        .path()
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("attachment")
        .to_string();
    let (extension, content_type) = media::outbound_media_kind(&filename);
    let id = format!("{}.{}", Uuid::new_v4(), extension);

    tokio::fs::create_dir_all(attachments_dir)
        .await
        .map_err(|error| format!("failed to create attachment directory: {error}"))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        tokio::fs::set_permissions(attachments_dir, std::fs::Permissions::from_mode(0o700))
            .await
            .map_err(|error| format!("failed to secure attachment directory: {error}"))?;
    }

    let temp_path = attachments_dir.join(format!(".{id}.tmp"));
    let final_path = attachments_dir.join(&id);
    if let Err(error) = write_attachment_snapshot(&temp_path, attachment.bytes()).await {
        let _ = tokio::fs::remove_file(&temp_path).await;
        return Err(format!("failed to write attachment: {error}"));
    }
    if let Err(error) = tokio::fs::rename(&temp_path, &final_path).await {
        let _ = tokio::fs::remove_file(&temp_path).await;
        return Err(format!("failed to store attachment: {error}"));
    }

    tracing::debug!(
        attachment_id = %id,
        size,
        "stored web attachment"
    );

    Ok(AttachmentInfo {
        id,
        filename,
        content_type: content_type.to_string(),
        size_bytes: size as u64,
    })
}

/// Serves one stored attachment.
///
/// The id is an opaque `{uuid}.{ext}` token generated by the Web adapter.
/// Only canonical UUIDs with an extension accepted by the media map are
/// served, so the request cannot escape the attachments directory. Audio is
/// served inline for `<audio>` playback; everything else is a download.
///
/// # Errors
///
/// Returns `404 attachment_not_found` for a malformed id or a missing file,
/// and `500 internal_error` when the file cannot be read.
pub(super) async fn get_attachment(
    State(state): State<WebState>,
    AxumPath(id): AxumPath<String>,
) -> Result<Response<Body>, ApiError> {
    let (_, content_type) =
        parse_attachment_id(&id).ok_or_else(|| not_found("attachment_not_found"))?;

    let path = state.app_state.config.attachments_dir().join(&id);
    let file = match tokio::fs::File::open(&path).await {
        Ok(file) => file,
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            return Err(not_found("attachment_not_found"));
        }
        Err(error) => {
            tracing::warn!(%error, attachment_id = %id, "failed to open attachment");
            return Err(internal_error());
        }
    };
    let metadata = match file.metadata().await {
        Ok(metadata) => metadata,
        Err(error) => {
            tracing::warn!(%error, attachment_id = %id, "failed to stat attachment");
            return Err(internal_error());
        }
    };
    if !metadata.is_file() {
        return Err(not_found("attachment_not_found"));
    }

    let disposition = if content_type.starts_with("audio/") {
        "inline"
    } else {
        "attachment"
    };
    let mut response = Response::new(Body::from_stream(ReaderStream::new(file)));
    *response.status_mut() = StatusCode::OK;
    let headers = response.headers_mut();
    headers.insert(header::CONTENT_TYPE, HeaderValue::from_static(content_type));
    headers.insert(
        header::CONTENT_LENGTH,
        HeaderValue::from_str(&metadata.len().to_string()).map_err(|error| {
            tracing::warn!(%error, attachment_id = %id, "invalid attachment length");
            internal_error()
        })?,
    );
    headers.insert(
        header::CONTENT_DISPOSITION,
        HeaderValue::from_str(&format!("{disposition}; filename=\"{id}\"")).map_err(|error| {
            tracing::warn!(%error, attachment_id = %id, "invalid attachment disposition");
            internal_error()
        })?,
    );
    headers.insert(
        header::CACHE_CONTROL,
        HeaderValue::from_static(ATTACHMENT_CACHE_CONTROL),
    );
    headers.insert(
        "x-content-type-options",
        HeaderValue::from_static("nosniff"),
    );
    Ok(response)
}

/// Validates an attachment id and returns its extension and content type.
///
/// The canonical hyphenated UUID form is required so ids such as
/// `urn:uuid:...` or a path fragment never reach the filesystem.
fn parse_attachment_id(raw: &str) -> Option<(&str, &'static str)> {
    let (stem, extension) = raw.rsplit_once('.')?;
    let uuid = Uuid::parse_str(stem).ok()?;
    if uuid.hyphenated().to_string() != stem {
        return None;
    }
    if extension.is_empty()
        || extension.len() > 8
        || !extension.bytes().all(|byte| byte.is_ascii_alphanumeric())
    {
        return None;
    }
    media::attachment_content_type(extension).map(|content_type| (extension, content_type))
}

#[cfg(test)]
mod storage_tests {
    use super::*;

    fn prepared(path: &Path, bytes: &[u8]) -> PreparedAttachment {
        PreparedAttachment::new(path.to_path_buf(), bytes.to_vec())
    }

    #[test]
    fn web_attachment_size_limit_is_inclusive() {
        // Arrange / Act / Assert
        assert!(validate_web_attachment_size(MAX_WEB_ATTACHMENT_BYTES).is_ok());
        let error =
            validate_web_attachment_size(MAX_WEB_ATTACHMENT_BYTES + 1).expect_err("over the limit");
        assert!(error.contains("50 MiB"), "{error}");
    }

    #[tokio::test]
    async fn store_attachment_snapshots_audio_with_opaque_id() {
        // Arrange
        let dir = tempfile::tempdir().expect("tempdir");
        let attachments_dir = dir.path().join("attachments");
        let source = dir.path().join("reply.mp3");
        std::fs::write(&source, b"audio-bytes").expect("source");
        let attachment = prepared(&source, b"audio-bytes");

        // Act
        let info = store_attachment(&attachments_dir, &attachment)
            .await
            .expect("store");

        // Assert: the stored name is the opaque id, not the source path.
        assert!(info.id.ends_with(".mp3"), "{info:?}");
        assert_eq!(info.filename, "reply.mp3");
        assert_eq!(info.content_type, "audio/mpeg");
        assert_eq!(info.size_bytes, 11);
        let stored = std::fs::read(attachments_dir.join(&info.id)).expect("stored attachment");
        assert_eq!(stored, b"audio-bytes");
    }

    #[tokio::test]
    async fn store_attachment_falls_back_to_bin_for_unknown_extension() {
        // Arrange
        let dir = tempfile::tempdir().expect("tempdir");
        let attachments_dir = dir.path().join("attachments");
        let source = dir.path().join("notes.pdf");
        std::fs::write(&source, b"pdf").expect("source");
        let attachment = prepared(&source, b"pdf");

        // Act
        let info = store_attachment(&attachments_dir, &attachment)
            .await
            .expect("store");

        // Assert
        assert!(info.id.ends_with(".bin"), "{info:?}");
        assert_eq!(info.content_type, "application/octet-stream");
    }

    #[cfg(unix)]
    #[tokio::test]
    async fn store_attachment_uses_owner_only_permissions() {
        // Arrange
        use std::os::unix::fs::PermissionsExt;
        let dir = tempfile::tempdir().expect("tempdir");
        let attachments_dir = dir.path().join("attachments");
        let source = dir.path().join("reply.mp3");
        std::fs::write(&source, b"audio").expect("source");
        let attachment = prepared(&source, b"audio");

        // Act
        let info = store_attachment(&attachments_dir, &attachment)
            .await
            .expect("store");

        // Assert
        let dir_mode = std::fs::metadata(&attachments_dir)
            .expect("dir metadata")
            .permissions()
            .mode()
            & 0o777;
        let file_mode = std::fs::metadata(attachments_dir.join(&info.id))
            .expect("file metadata")
            .permissions()
            .mode()
            & 0o777;
        assert_eq!(dir_mode, 0o700, "attachments directory must be owner-only");
        assert_eq!(file_mode, 0o600, "attachment must be owner-only");
    }

    #[tokio::test]
    async fn store_attachment_reports_directory_failure() {
        // Arrange: a regular file blocks the attachments directory.
        let dir = tempfile::tempdir().expect("tempdir");
        let blocked = dir.path().join("attachments");
        std::fs::write(&blocked, b"not a directory").expect("blocker");
        let source = dir.path().join("reply.mp3");
        std::fs::write(&source, b"audio").expect("source");
        let attachment = prepared(&source, b"audio");

        // Act
        let error = store_attachment(&blocked, &attachment)
            .await
            .expect_err("must fail");

        // Assert
        assert!(
            error.contains("failed to create attachment directory"),
            "{error}"
        );
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parse_attachment_id_accepts_canonical_uuid_and_audio_extension() {
        // Arrange
        let id = "00000000-0000-4000-8000-000000000000.mp3";

        // Act / Assert
        assert_eq!(parse_attachment_id(id), Some(("mp3", "audio/mpeg")));
    }

    #[test]
    fn parse_attachment_id_rejects_paths_and_unknown_extensions() {
        // Arrange / Act / Assert
        assert_eq!(
            parse_attachment_id("../00000000-0000-4000-8000-000000000000.mp3"),
            None
        );
        assert_eq!(
            parse_attachment_id("00000000-0000-4000-8000-000000000000.html"),
            None
        );
        assert_eq!(parse_attachment_id("not-a-uuid.mp3"), None);
        assert_eq!(
            parse_attachment_id("00000000-0000-4000-8000-000000000000"),
            None
        );
    }
}
